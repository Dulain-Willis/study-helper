#!/usr/bin/env python3
"""Generate lesson_preview/INDEX.md: file -> sections -> sub-sections, with line ranges.

Run from anywhere:  python3 scripts/build_lesson_index.py
Re-run whenever lessons change (line numbers go stale otherwise).
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LESSONS = ROOT / "lesson_preview"
OUT = LESSONS / "INDEX.md"


def headings(path):
    """Return [(level, title, start_line)], skipping fenced code blocks."""
    out, in_fence = [], False
    lines = path.read_text(encoding="utf-8").splitlines()
    for i, line in enumerate(lines, 1):
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        elif not in_fence and (m := re.match(r"^(#{1,3})\s+(.*\S)", line)):
            out.append((len(m.group(1)), m.group(2), i))
    return out, len(lines)


def main():
    parts = [
        "# Lesson Index\n",
        "Generated by `scripts/build_lesson_index.py`; do not edit by hand.\n",
        "Format: `L<start>-<end>` is the line range inside that file. "
        "Read just that range (Read tool offset/limit) instead of the whole file.\n",
    ]
    for path in sorted(LESSONS.glob("*.md")):
        if path.name == "INDEX.md":
            continue
        hs, total = headings(path)
        if not hs:
            continue
        # end of each heading = line before the next heading of same or higher level
        ends = []
        for idx, (lvl, _, start) in enumerate(hs):
            end = total
            for lvl2, _, s2 in hs[idx + 1:]:
                if lvl2 <= lvl:
                    end = s2 - 1
                    break
            ends.append(end)
        title = next((t for l, t, _ in hs if l == 1), path.stem)
        parts.append(f"\n## `{path.name}`: {title} ({total} lines)\n")
        seen_h2 = False
        for (lvl, text, start), end in zip(hs, ends):
            if lvl == 1:
                continue
            if lvl == 2:
                seen_h2 = True
            # an ### with no ## above it (e.g. directly under the title) is top-level
            indent = "  " if (lvl == 3 and seen_h2) else ""
            parts.append(f"{indent}- L{start}-{end} {text}")
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
